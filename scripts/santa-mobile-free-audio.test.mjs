import test from 'node:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import ffmpeg from 'ffmpeg-static';
import { mobileFreeRenderArgs } from './santa-audio-mobile-filters.mjs';
import { createMobileFreeMessageHandler, mobileFreeBells } from '../server/mobile/free-message.js';
import { createMobileHandler } from '../server/mobile/handler.js';

const hash = bytes => createHash('sha256').update(bytes).digest('hex');

test('iPhone default free handler uses the unchanged pre-website recipe and bell bytes', async () => {
  // Fingerprints of the complete arguments generated by the pre-change recipe,
  // with fixed placeholder paths, protect every filter, encoder and option.
  for (const [prepared, expected] of [
    [false, '7f351e856847b9481779f9624b14e62e095f433cf0f88feedab6cd5125fb5dc8'],
    [true, 'e038f6e9513e3ae7b9103d9628e89478881755d528a31fcc7c7f7981f4fdbbb1'],
  ]) {
    assert.equal(hash(JSON.stringify(mobileFreeRenderArgs('intro', 'name', 'outro', 'bells', 'output', prepared))), expected);
  }
  assert.equal(hash(await readFile(mobileFreeBells)),
    '0896b5c703b2c4b335db5e43ea3894fc34b22c5e1f7f87281edc8017f764e541');
  const source = await readFile('server/mobile/handler.js', 'utf8');
  assert.match(source, /free = createMobileFreeMessageHandler\(\)/);
  assert.doesNotMatch(source, /createSantaMessageHandler/);
});

test('native free endpoint retains complete old MP3s and duration for both standard endings and November', { timeout: 120000 }, async () => {
  const record = { id: 'arabella', name: 'Arabella', source: 'local' };
  let date;
  const finished = [];
  const free = createMobileFreeMessageHandler({ resolve: async () => record }, null, {
    now: () => new Date(date), limit: async () => {}, verify: token => token,
    authorize: async () => ({ subject: 'controlled-native-fixture' }),
    reserve: async () => ({}), finish: async (_, success) => finished.push(success),
  });
  const token = 'a'.repeat(43);
  const handler = createMobileHandler({
    free, limit: async () => {},
    getStore: () => ({ session: async bearer => {
      assert.equal(bearer, token);
      return { customerId: 'controlled-fixture' };
    } }),
  });
  const server = createServer(handler);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const directory = await mkdtemp(join(tmpdir(), 'native-free-audio-'));
  const pcm = args => {
    const result = spawnSync(ffmpeg, ['-v', 'error', ...args, '-ar', '48000', '-ac', '2', '-f', 'f32le', '-'],
      { timeout: 20000, maxBuffer: 40 * 1024 * 1024 });
    assert.equal(result.status, 0, result.stderr?.toString());
    return result.stdout;
  };
  try {
    for (const ending of [1, 2, 'nov']) {
      date = ending === 'nov' ? '2026-11-05T12:00:00Z' : '2026-12-05T12:00:00Z';
      const response = await fetch(`http://127.0.0.1:${server.address().port}/?action=free`, {
        method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: 'arabella', selectionToken: 'arabella', outro: ending === 2 ? 2 : 1 }),
      });
      assert.equal(response.status, 200);
      assert.equal(response.headers.get('content-type'), 'audio/mpeg');
      assert.match(response.headers.get('cache-control'), /no-store/);
      const audio = Buffer.from(await response.arrayBuffer());
      const output = join(directory, 'reference.mp3');
      const args = mobileFreeRenderArgs('server/santa-audio/prepared/intro.wav',
        'server/santa-audio/names/arabella.wav', `server/santa-audio/prepared/outro-${ending}.wav`,
        mobileFreeBells, output, true);
      const reference = spawnSync(ffmpeg, args, { timeout: 20000 });
      assert.equal(reference.status, 0, reference.stderr?.toString());
      assert.equal(hash(audio), hash(await readFile(output)), 'Native response is the exact preserved recipe output.');
      const sourceFrames = ['prepared/intro.wav', 'names/arabella.wav', `prepared/outro-${ending}.wav`]
        .reduce((sum, file) => sum + pcm(['-i', `server/santa-audio/${file}`]).length / 8, 0);
      const frames = pcm(['-i', output]).length / 8;
      assert.ok(Math.abs(frames - sourceFrames) <= 3, 'Native audio has no new lead-in or tail.');
      console.info('[native free unchanged]', { ending, seconds: frames / 48000 });
    }
    assert.deepEqual(finished, [true, true, true]);
  } finally {
    await new Promise(resolve => { server.closeAllConnections(); server.close(resolve); });
    await rm(directory, { recursive: true, force: true });
  }
});
